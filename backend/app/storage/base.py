from pathlib import Path
from typing import Any, Protocol


class ArtifactStorage(Protocol):
    def document_dir(self, document_id: str) -> Path: ...
    def source_path(self, document_id: str, extension: str | None = None) -> Path: ...
    async def write_json(
        self, document_id: str, relative_path: str, payload: dict[str, Any]
    ) -> Path: ...
    async def read_json(
        self, document_id: str, relative_path: str
    ) -> dict[str, Any]: ...
    def exists(self, document_id: str, relative_path: str) -> bool: ...
    async def delete_document(self, document_id: str) -> None: ...
